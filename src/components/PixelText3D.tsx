interface PixelText3DProps {
  text: string;
  scale?: number;
}

function TextMesh({ text, scale = 1 }: PixelText3DProps) {
  // Calculate text dimensions and centering
  const textMetrics = useMemo(() => {
    const cleanText = text.toUpperCase();
    const letterWidth = 5;
    const letterSpacing = 1;
    const totalWidth = cleanText.length * letterWidth + (cleanText.length - 1) * letterSpacing;
    const totalHeight = 7;
    
    return {
      cleanText,
      totalWidth,
      totalHeight,
      letterWidth,
      letterSpacing,
    };
  }, [text]);

  // Generate cubes with automatic centering
  const cubes = useMemo(() => {
    const cubeArray = [];
    const cubeSize = 0.3 * scale;
    const spacing = 0.35 * scale;
    const letterSpacing = (textMetrics.letterWidth + textMetrics.letterSpacing) * spacing;
    
    // Calculate starting X position to center the text
    const totalTextWidth = (textMetrics.totalWidth - 1) * spacing;
    const startX = -totalTextWidth / 2;

    let currentX = startX;

    // Process each character in the text
    for (let charIndex = 0; charIndex < textMetrics.cleanText.length; charIndex++) {
      const char = textMetrics.cleanText[charIndex];
      const pattern = LETTER_PATTERNS[char];

      if (pattern) {
        // Generate cubes for this letter
        for (let row = 0; row < pattern.length; row++) {
          for (let col = 0; col < pattern[row].length; col++) {
            if (pattern[row][col] === 1) {
              const x = currentX + (col * spacing);
              const y = ((pattern.length / 2 - row) * spacing);
              const z = 0;

              cubeArray.push(
                <mesh key={`${charIndex}-${row}-${col}`} position={[x, y, z]}>
                  <boxGeometry args={[cubeSize, cubeSize, cubeSize]} />
                  <meshLambertMaterial color="#ff0000" />
                </mesh>
              );
            }
          }
        }
      }

      // Move to next letter position
      currentX += letterSpacing;
    }

    return cubeArray;
  }, [textMetrics, scale]);

  return <group>{cubes}</group>;
}

export default function PixelText3D({ text, scale }: PixelText3DProps) {
  // Calculate responsive scale based on text length and screen size
  const responsiveScale = useMemo(() => {
    const baseScale = scale || 1;
    const textLength = text.length;
    
    // Adjust scale based on text length to keep it fitting nicely
    if (textLength > 15) return baseScale * 0.6;
    if (textLength > 10) return baseScale * 0.8;
    if (textLength > 5) return baseScale * 0.9;
    return baseScale;
  }, [text, scale]);

  return (
    <Canvas
      camera={{ position: [0, 0, 15], fov: 50 }}
      style={{ background: 'transparent' }}
    >
      <ambientLight intensity={0.6} />
      <directionalLight 
        position={[5, 5, 5]} 
        intensity={0.8}
        castShadow
      />
      <TextMesh text={text} scale={responsiveScale} />
    </Canvas>
  );
}